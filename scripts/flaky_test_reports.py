# Використання ШІ: Codex додав порівняння JUnit-звітів.
# Перевірка: pytest зі стабільними, нестабільними й неповними раундами.
"""Compare JUnit results from repeated test runs on the same commit."""

import argparse
from collections import defaultdict
from pathlib import Path
from xml.etree import ElementTree  # nosec B405: reports are generated by local test processes


def read_cases(path):
    root = ElementTree.parse(path).getroot()  # nosec B314: local test reports
    cases = {}
    for case in root.iter("testcase"):
        name = f"{case.attrib.get('classname', '')}::{case.attrib['name']}"
        if name in cases:
            raise ValueError(f"Duplicate test identifier: {name}")
        if case.find("failure") is not None or case.find("error") is not None:
            status = "failed"
        else:
            status = "skipped" if case.find("skipped") is not None else "passed"
        cases[name] = status
    if not cases:
        raise ValueError("JUnit report contains no test cases")
    return cases


def compare(directory, suite, rounds):
    by_round, incomplete = {}, {}
    observed = defaultdict(set)
    for index in range(1, rounds + 1):
        stem = directory / f"{suite}-{index}"
        try:
            code = int(stem.with_suffix(".exit").read_text(encoding="utf-8"))
            cases = read_cases(stem.with_suffix(".xml"))
            if code not in (0, 1) or (code == 1) != ("failed" in cases.values()):
                raise ValueError(f"Exit status {code} is inconsistent with a complete report")
        except (OSError, ValueError, KeyError, ElementTree.ParseError) as error:
            incomplete[index] = str(error)
            continue
        by_round[index] = cases
        for name, status in cases.items():
            observed[name].add(status)
    for index, cases in by_round.items():
        missing = observed.keys() - cases.keys()
        if missing:
            incomplete[index] = f"{len(missing)} test case(s) missing from this round"
    return {
        "test_count": len(observed),
        "flaky": {name: sorted(statuses) for name, statuses in sorted(observed.items()) if len(statuses) > 1},
        "stable_failures": sorted(
            name
            for name, statuses in observed.items()
            if statuses == {"failed"} and all(name in cases for cases in by_round.values())
        ),
        "incomplete": incomplete,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reports", type=Path)
    parser.add_argument("summary", type=Path)
    parser.add_argument("--sha", required=True)
    args = parser.parse_args()
    lines = ["# Repeated test results", "", f"Commit: `{args.sha}`", ""]
    failed = False
    for suite in ("backend", "frontend"):
        result = compare(args.reports, suite, 5)
        lines.extend([f"## {suite.title()}", "", f"Observed test cases: {result['test_count']}", ""])
        for label, entries in (
            ("Changed outcomes", [f"{name}: {', '.join(states)}" for name, states in result["flaky"].items()]),
            ("Consistent failures in available rounds", result["stable_failures"]),
            ("Incomplete rounds", [f"Round {n}: {reason}" for n, reason in result["incomplete"].items()]),
        ):
            lines.extend([f"### {label}", "", *([f"- {entry}" for entry in entries] or ["None"]), ""])
            failed |= bool(entries)
    lines += ["## Використання ШІ", "", "Codex підготував аналіз звітів. Класифікацію перевірено тестами pytest.", ""]
    output = "\n".join(lines)
    args.summary.write_text(output, encoding="utf-8")
    print(output)
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main())
